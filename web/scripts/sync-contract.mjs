// Copy the contract to the plugin builds.
//
// The shell owns `src/portal/contract.ts`; each plugin builds against its own
// copy, so the two never import each other's source tree. Copying by hand is how
// the copies drifted (a field added here, missing there, discovered only when a
// plugin's `tsc` failed on something unrelated). This script is the only supported
// way to update them.
//
//   node scripts/sync-contract.mjs          # write the copies
//   node scripts/sync-contract.mjs --check  # report drift without writing
//
// The only edit it makes: the shell's own `DockId` import is inlined, because a
// plugin must not reach into `../workbench/types`.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const webRoot = join(here, '..')
const repoRoot = join(webRoot, '..', '..')
const source = join(webRoot, 'src', 'portal', 'contract.ts')

const targets = [
  join(repoRoot, 'nanoadmin', 'ui', 'src', 'contract.ts'),
  join(repoRoot, 'nanoauth', 'ui', 'src', 'contract.ts'),
  join(repoRoot, 'nanoworkspace', 'ui', 'src', 'contract.ts'),
]

const header = `// The portal's page and panel contract, copied.
//
// \`nanoportal/web/src/portal/contract.ts\` is the source of truth; this build keeps
// its own copy so the two do not import each other. A field added there must be
// copied here before a page or panel may rely on it — the plugin's \`tsc\` fails
// otherwise, which is the check that keeps them in step.
//
// Generated by \`nanoportal/web/scripts/sync-contract.mjs\`; do not edit by hand.
//
// \`DockId\` is inlined: a plugin must not import the shell's source tree.

`

const dockImport = "import type { DockId } from '../workbench/types'\n"
const inlineDock =
  "\n/** The docks a panel may open in; the shell owns the list. */\ntype DockId = 'left' | 'center' | 'right' | 'bottom'\n"

const body = readFileSync(source, 'utf8')
if (!body.includes(dockImport)) {
  throw new Error(`the source contract no longer imports DockId the expected way:\n  ${dockImport.trim()}`)
}
const rendered = header + body.replace(dockImport, inlineDock)

let drifted = 0
for (const target of targets) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // A missing copy is drift too; --check reports it.
  }
  if (current === rendered) {
    continue
  }
  drifted += 1
  if (process.argv.includes('--check')) {
    console.log(`drift: ${relative(repoRoot, target)}`)
    continue
  }
  writeFileSync(target, rendered)
  console.log(`wrote ${relative(repoRoot, target)}`)
}

if (process.argv.includes('--check')) {
  process.exit(drifted === 0 ? 0 : 1)
}
