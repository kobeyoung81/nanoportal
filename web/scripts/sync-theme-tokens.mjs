// 从 src/styles/tokens.json 生成：
//   src/styles/tokens.structure.css  （结构：只有几何）
//   src/styles/tokens.palette.css    （配色：只有色值 + 旧名快照）
//   index.html 的 theme-color
// 说明：旧名（--background/--primary…）与 --c-* 同源生成，保证回退块测试与现有组件都不用改。
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(process.cwd())
const SRC = path.join(ROOT, 'src/styles')

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase()).replace(/([a-z])(\d)/g, '$1-$2')

const HEADER = '/* GENERATED by scripts/sync-theme-tokens.mjs from src/styles/tokens.json — do not edit. */\n'

function structureCss(tokens) {
  const blocks = []
  for (const [id, s] of Object.entries(tokens.structure)) {
    const base = Object.entries(s).filter(([, v]) => typeof v === 'string')
    blocks.push(`[data-structure='${id}'] {\n${base.map(([k, v]) => `  --ui-${k}: ${v};`).join('\n')}\n}`)
    for (const mode of ['light', 'dark']) {
      const shadows = Object.entries(s).filter(([, v]) => typeof v === 'object')
      if (shadows.length === 0) continue
      blocks.push(
        `[data-structure='${id}'][data-theme='${mode}'] {\n` +
          shadows.map(([k, v]) => `  --ui-${k}: ${v[mode]};`).join('\n') +
          '\n}',
      )
    }
  }
  return HEADER + blocks.join('\n\n') + '\n'
}

function paletteCss(tokens) {
  const blocks = []
  for (const [id, modes] of Object.entries(tokens.palette)) {
    for (const mode of ['light', 'dark']) {
      const p = modes[mode]
      const selector = mode === 'light'
        ? `:root,\n[data-palette='${id}'][data-theme='light']`
        : `.dark,\n[data-palette='${id}'][data-theme='dark']`
      const semantic = Object.entries(p).map(([k, v]) => `  --c-${kebab(k)}: ${v};`)
      const legacy = Object.entries(tokens.legacy)
        .filter(([, from]) => p[from] != null)
        .map(([to, from]) => `  --${to}: ${p[from]};`)
      // 阴影：形状归结构，颜色归配色；旧名 `--shadow-*` 直接指过去。
      legacy.push(
        '  --radius: var(--ui-radius);',
        '  --shadow-1: var(--ui-shadow-1);',
        '  --shadow-2: var(--ui-shadow-2);',
      )
      blocks.push(
        `${selector} {\n${semantic.join('\n')}\n\n  /* 旧名快照（与 --c-* 同源；P5 删除） */\n${legacy.join('\n')}\n}`,
      )
    }
  }
  return HEADER + blocks.join('\n\n') + '\n'
}

// 作品库（nanoartifacts）用的是自己的一套变量名，值来自同一份 tokens.json。
// 它是 iframe，拿不到 host 的继承，所以必须自带一份；由 check-tokens 守住一致性。
function artifactsCss(tokens) {
  const p = tokens.palette.slate
  const radius = tokens.structure.graphite['radius-lg']
  const blocks = []
  for (const mode of ['light', 'dark']) {
    const c = p[mode]
    const selector = mode === 'light'
      ? `:root,\n[data-palette='slate'][data-theme='light']`
      : `.dark,\n[data-palette='slate'][data-theme='dark']`
    blocks.push(`${selector} {
  color-scheme: ${mode};
  --background: ${c.canvas};
  --foreground: ${c.text};
  --card: ${c.surface};
  --border: ${c.border};
  --muted: ${c.surface2};
  --muted-foreground: ${c.text2};
  --primary: ${c.accent};
  --primary-foreground: ${c.onAccent};
  --primary-tint: ${c.primaryTint};
  --accent: ${c.hoverSurface};
  --success: ${c.success};
  --warning: ${c.warning};
  --danger: ${c.danger};
  --info: ${c.info};
  --radius: ${radius};
  --radius-xl: calc(${radius} + 0.25rem);
}`)
  }
  return HEADER + blocks.join('\n\n') + '\n'
}

export function render(tokens) {
  return {
    structure: structureCss(tokens),
    palette: paletteCss(tokens),
    artifacts: artifactsCss(tokens),
  }
}

export function readTokens() {
  return JSON.parse(fs.readFileSync(path.join(SRC, 'tokens.json'), 'utf8'))
}

function main() {
  const tokens = readTokens()
  const { structure, palette, artifacts } = render(tokens)
  const artifactsPath = path.resolve(ROOT, '../../nanoartifacts/web/src/theme.generated.css')
  if (fs.existsSync(path.dirname(artifactsPath))) fs.writeFileSync(artifactsPath, artifacts)
  fs.mkdirSync(SRC, { recursive: true })
  fs.writeFileSync(path.join(SRC, 'tokens.structure.css'), structure)
  fs.writeFileSync(path.join(SRC, 'tokens.palette.css'), palette)

  const slate = tokens.palette.slate
  const htmlPath = path.join(ROOT, 'index.html')
  let html = fs.readFileSync(htmlPath, 'utf8')
  html = html
    .replace(/(<meta name="theme-color" media="\(prefers-color-scheme: light\)" content=")[^"]*(")/, `$1${slate.light.canvas}$2`)
    .replace(/(<meta name="theme-color" media="\(prefers-color-scheme: dark\)" content=")[^"]*(")/, `$1${slate.dark.canvas}$2`)
  fs.writeFileSync(htmlPath, html)

  console.log('tokens: structure + palette written, theme-color synced')
}

if (process.argv[1] && process.argv[1].endsWith('sync-theme-tokens.mjs')) main()
